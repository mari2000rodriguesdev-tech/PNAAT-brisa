# Operadores Lógicos
# Os operadores lógicos permitem criar, combinar e avaliar expressões booleanas. Python suporta os seguintes operadores lógicos:

a = True
b = False

# AND: Retorna True se ambas as expressões forem verdadeiras
a and b

# OR: Retorna True se pelo menos uma das expressões for verdadeira
a or b

# NOT: Inverte o valor booleano da expressão
not a
